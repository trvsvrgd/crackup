const copied = new Set(), modules = [];
function copyModule(name, from = path.join(root, 'package.json')) {
  // Locate installed package directories even for npm packages named like Node builtins (buffer).
  let parent = path.dirname(from), directory;
  while (true) {
    const candidate = path.join(parent, 'node_modules', name);
    if (fs.existsSync(path.join(candidate, 'package.json'))) { directory = candidate; break; }
    const next = path.dirname(parent); if (next === parent) throw new Error(`Cannot resolve package ${name}`); parent = next;
  }
  if (copied.has(directory)) return;
  copied.add(directory);
  const relative = path.relative(root, directory);
  if (!relative.startsWith(`node_modules${path.sep}`)) throw new Error(`Dependency outside installed workspace: ${name}`);
  const metadata = JSON.parse(fs.readFileSync(path.join(directory, 'package.json'), 'utf8'));
  fs.cpSync(directory, path.join(app, relative), { recursive: true });
  modules.push({ name, version: metadata.version, path: relative.replaceAll('\\', '/'), license: metadata.license });
  for (const dependency of Object.keys(metadata.dependencies ?? {})) copyModule(dependency, path.join(directory, 'package.json'));
}
